alter table public.quests add column if not exists fields text[] not null default '{}';

-- これまでのクエストは、今の一覧にある種別をそのまま1つ目の分野にする
-- （廃止した種別のクエストは空のまま。アプリは quest_type を分野として扱う）
update public.quests
set fields = array[quest_type]
where fields = '{}'
  and quest_type in ('スポーツ・運動', '音楽・演奏', '文化・芸術', 'ものづくり・技術', '学び・研究',
                     '自然・アウトドア', '国際交流・語学', '地域・ボランティア', '企画・イベント運営', '食・料理', 'その他');

